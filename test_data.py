def status_for(pct: int) -> tuple[str, str]:
    """Возвращает (иконка-статус, подпись) по проценту.

    Процент — это НЕ «уровень вещества в организме», а то, насколько
    сильно у человека выражены симптомы, связанные с его нехваткой.
    Поэтому чем МЕНЬШЕ процент — тем лучше (меньше признаков дефицита).
    """
    if pct < 30:
        return "🟢", "в норме — выраженных признаков нехватки нет"
    if pct < 55:
        return "🟡", "лёгкие признаки нехватки"
    if pct < 75:
        return "🟠", "умеренно выраженная нехватка"
    return "🔴", "сильно выраженная нехватка"


from urllib.parse import quote


def _wb_link(query: str) -> str:
    return f"https://www.wildberries.ru/catalog/0/search.aspx?search={quote(query)}"


def _ozon_link(query: str) -> str:
    return f"https://www.ozon.ru/search/?text={quote(query)}"


def _market_links(query: str) -> str:
    return (
        f'  ↳ <a href="{_wb_link(query)}">WB</a> · '
        f'<a href="{_ozon_link(query)}">Ozon</a>'
    )


